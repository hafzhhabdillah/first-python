# sistem input
angka_pertama = float(input("masukan angka pertama : "))
angka_kedua = float(input("masukan angka kedua : "))

# operasi
tambah = angka_pertama + angka_kedua
kurang = angka_pertama - angka_kedua
kali = angka_pertama * angka_kedua
bagi = angka_pertama / angka_kedua
sisa_bagi = angka_pertama % angka_kedua

# sistem output
print("\n hasil perhitungan :")
print("penjumalahan : ", tambah)
print("Pengurangan : ", kurang)
print("Perkalin : ", kali)
print("Pembagian : ", bagi)
print("Sisa bagi : ", sisa_bagi)